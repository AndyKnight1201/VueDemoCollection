export function getInitialLocale(storage = globalThis.localStorage) {
  try {
    return storage?.getItem(LOCALE_STORAGE_KEY) === 'en' ? 'en' : 'zh-TW'
  } catch {
    return 'zh-TW'
  }
}

export function useLocale() {
  const value = inject(localeKey)
  if (!value) throw new Error('Locale provider is unavailable')
  return value
}
